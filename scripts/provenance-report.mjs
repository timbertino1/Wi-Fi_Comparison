// Writes docs/provenance-report.md: every claim with its sources, locations, derivation and
// verification status, grouped by the tabs that use it (research.md R16).
// Usage: node scripts/provenance-report.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadContent, CLAIM_RE } from './validate-content.mjs';
import { recompute } from './derivations.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'docs', 'provenance-report.md');

const TIER_LABEL = { 1: 'Tier 1 (standards body / regulator)', 2: 'Tier 2 (peer-reviewed / health authority)' };
const METHOD_LABEL = { stated: 'Stated in source', derived: 'Derived', illustrative: 'Illustrative' };

/** Most recent verification date in the content, so the report is identical wherever it is built. */
function latestVerification(content) {
  const dates = content.claims.map((c) => c.verification?.verifiedOn).filter(Boolean).sort();
  return dates.at(-1) ?? 'none yet';
}

function claimUsage(content) {
  const usage = new Map(content.claims.map((c) => [c.id, new Set()]));
  const mark = (id, label) => usage.get(id)?.add(label);
  for (const tab of content.tabs) {
    const label = `${tab.order}. ${tab.title}`;
    for (const [, id] of JSON.stringify(tab).matchAll(new RegExp(CLAIM_RE.source, 'g'))) mark(id, label);
    for (const k of tab.keyFigures ?? []) for (const id of Object.values(k.claimIds ?? {})) mark(id, label);
  }
  for (const s of content.scenarios) for (const [, id] of JSON.stringify(s).matchAll(new RegExp(CLAIM_RE.source, 'g'))) mark(id, 'Healthcare scenarios');
  for (const g of content.generations) if (g.yearClaimId) mark(g.yearClaimId, 'Generation timeline');
  // Inputs inherit the usage of the derived claims that need them.
  for (const c of content.claims) {
    for (const id of Object.values(c.derivation?.inputs ?? {})) for (const l of usage.get(c.id) ?? []) mark(id, l);
  }
  return usage;
}

export function buildReport(content = loadContent()) {
  const refById = new Map(content.references.map((r) => [r.id, r]));
  const claimById = new Map(content.claims.map((c) => [c.id, c]));
  const pubById = new Map(content.sourcePolicy.publishers.map((p) => [p.id, p]));
  const usage = claimUsage(content);
  const verified = content.claims.filter((c) => c.verification?.verifiedOn).length;

  const lines = [];
  lines.push('# Provenance Report', '');
  lines.push('<!-- Generated by `npm run provenance`. Do not edit by hand; CI checks that it is current. -->', '');
  lines.push(`Latest verification: **${latestVerification(content)}** · Claims: **${content.claims.length}** · Verified: **${verified}** · References: **${content.references.length}**`, '');
  lines.push('Source policy: technical claims require a Tier 1 source (standards bodies and regulators); healthcare-context claims require Tier 1 or Tier 2 (peer-reviewed with DOI, FDA, AAMI, WHO). Vendor material, wikis, blogs, forums, news, analyst marketing and AI-generated text are never cited. See [source-policy.md](source-policy.md).', '');

  const describe = (c) => {
    const out = [];
    const value = c.value === null ? '—' : `${c.value}${c.unit ? ` ${c.unit}` : ''}`;
    out.push(`#### \`${c.id}\``, '');
    out.push(`- **Statement:** ${c.statement}`);
    out.push(`- **Value:** ${value}`);
    out.push(`- **Kind / method:** ${c.kind} · ${METHOD_LABEL[c.method] ?? c.method}`);
    out.push('- **Sources:**');
    for (const s of c.sources ?? []) {
      const r = refById.get(s.referenceId);
      if (!r) { out.push(`  - *(unknown reference ${s.referenceId})*`); continue; }
      const pub = pubById.get(r.publisher)?.name ?? r.publisher;
      out.push(`  - ${pub} — ${r.identifier}${r.edition ? `, ${r.edition}` : ''} — **${s.locator}** — ${TIER_LABEL[r.tier]} — ${r.access} — <${r.url}>`);
      if (s.excerpt) out.push(`    > ${s.excerpt}`);
    }
    if (c.derivation) {
      const d = c.derivation;
      const inputs = Object.entries(d.inputs ?? {}).map(([name, id]) => {
        const i = claimById.get(id);
        return `${name} = ${i?.value ?? '?'}${i?.unit ? ` ${i.unit}` : ''} (\`${id}\`)`;
      });
      const constants = Object.entries(d.constants ?? {}).map(([k, v]) => `${k} = ${v}`);
      let computed = '?';
      try {
        const values = { ...(d.constants ?? {}) };
        for (const [name, id] of Object.entries(d.inputs ?? {})) values[name] = claimById.get(id)?.value;
        computed = recompute(d.formula, values, d.rounding);
      } catch { /* reported by validation */ }
      out.push(`- **Derivation:** \`${d.formula}\` — ${d.explanation}`);
      out.push(`  - Inputs: ${[...inputs, ...constants].join('; ')}`);
      out.push(`  - Recomputed: ${computed}${c.unit ? ` ${c.unit}` : ''}`);
    }
    const v = c.verification ?? {};
    out.push(`- **Verification:** ${v.verifiedOn ? `verified ${v.verifiedOn} by ${v.verifiedBy}` : 'not yet verified'}${v.notes ? ` — ${v.notes}` : ''}`);
    out.push('');
    return out;
  };

  const groups = new Map();
  const unused = [];
  for (const c of [...content.claims].sort((a, b) => a.id.localeCompare(b.id))) {
    const where = [...(usage.get(c.id) ?? [])].sort();
    if (!where.length) unused.push(c);
    for (const w of where) {
      if (!groups.has(w)) groups.set(w, []);
      groups.get(w).push(c);
    }
  }
  const order = (label) => (/^\d+\./.test(label) ? Number(label.split('.')[0]) : label === 'Generation timeline' ? 0 : 99);
  for (const label of [...groups.keys()].sort((a, b) => order(a) - order(b) || a.localeCompare(b))) {
    lines.push(`## ${label}`, '');
    for (const c of groups.get(label)) lines.push(...describe(c));
  }
  if (unused.length) {
    lines.push('## Not yet used on the site', '');
    for (const c of unused) lines.push(...describe(c));
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = buildReport();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== report) {
      console.error('docs/provenance-report.md is out of date. Run `npm run provenance` and commit the result.');
      process.exit(1);
    }
    console.log('docs/provenance-report.md is current.');
  } else {
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, report);
    console.log(`Wrote docs/provenance-report.md (${report.split('\n').length} lines).`);
  }
}
