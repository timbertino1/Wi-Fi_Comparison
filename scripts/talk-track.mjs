// Builds the speaker talk track from content (contracts/talk-track.md, research P8): every chapter
// and step with what is on screen, what to say, technical depth, figures with sources and likely
// questions, plus key figures, glossary, claims register and references. Output is deterministic
// plain Markdown in docs/, never in dist/.
// Usage: node scripts/talk-track.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadContent, TERM_RE, CLAIM_RE, REF_RE } from './validate-content.mjs';
import { openerParts, lineageLead } from '../src/app/opener-text.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'docs/talk-track.md';

const QUALIFIER_LABEL = {
  theoretical: 'theoretical maximum',
  'specified-not-shipping': 'specified in the standard, not in current devices',
  optional: 'optional',
  illustrative: 'illustrative',
  regulatory: 'regulatory limit',
  normative: 'required by the standard',
  typical: 'typical'
};

export function buildTalkTrack(content = loadContent()) {
  const { tabs, scenarios, glossary, references, claims, generations } = content;
  const termById = new Map(glossary.map((g) => [g.id, g]));
  const claimById = new Map(claims.map((c) => [c.id, c]));
  const scenarioById = new Map(scenarios.map((s) => [s.id, s]));
  const genById = new Map(generations.map((g) => [g.id, g]));
  // References are numbered S1…Sn in file order; claims cite the references they rest on.
  const sourceNo = new Map(references.map((r, i) => [r.id, i + 1]));
  const marker = (refIds) => `[${[...new Set(refIds)].map((id) => `S${sourceNo.get(id)}`).join(', ')}]`;
  const claimMarker = (id) => marker((claimById.get(id)?.sources ?? []).map((s) => s.referenceId));

  /** Content markup → Markdown: term display text, citations as source markers, bold kept. */
  const md = (text) => (text ?? '')
    .replace(TERM_RE, (_, id, label) => label ?? termById.get(id)?.term ?? id)
    .replace(REF_RE, (_, id) => marker([id]))
    .replace(CLAIM_RE, (_, id) => claimMarker(id))
    .replace(/(?<=[^\s([])\[(S\d+)/g, ' [$1'); // a marker written straight after a word gets a space
  const sentence = (s) => (/[.!?…]$/.test(s) ? s : `${s}.`);
  const cell = (text) => md(String(text ?? '')).replace(/\s*\n+\s*/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
  const termsIn = (...texts) => [...new Set(texts.flatMap((t) => [...(t ?? '').matchAll(new RegExp(TERM_RE.source, 'g'))].map((m) => m[1])))];
  const claimsIn = (...texts) => [...new Set(texts.flatMap((t) => [...(t ?? '').matchAll(new RegExp(CLAIM_RE.source, 'g'))].map((m) => m[1])))];
  const value = (c) => (c.value === null || c.value === undefined ? '—' : `${c.value}${c.unit ? ` ${c.unit}` : ''}`);

  const out = [];
  const line = (s = '') => out.push(s);
  const chapters = tabs.filter((t) => t.kind !== 'references' && t.beats.length);

  line('# Wi-Fi 7 Explained — Talk Track');
  line();
  line('Generated from `content/` by `scripts/talk-track.mjs`. Do not edit this file; annotate the editable copy instead.');
  line('Source markers such as [S3] refer to the References section at the end.');
  line();
  line('## Contents');
  line();
  chapters.forEach((t, i) => line(`${i + 1}. ${t.title}`));
  line('- Generations · Glossary · Claims register · References');
  line();

  chapters.forEach((tab, ci) => {
    line(`## ${ci + 1}. ${tab.title}`);
    line();
    line(md(tab.summary));
    line();
    if (tab.opener) {
      const o = openerParts(tab, ci + 1, genById);
      const badge = o.badge ? ` · ${o.badge}` : '';
      line(`**Opener** (its own click): ${o.label} · ${o.tag}${badge} — ${tab.title}. ${sentence(md(tab.opener.promise))} The problem: ${sentence(md(tab.opener.problem))}`);
      line();
    }
    const lead = lineageLead(tab, genById);
    if (lead) {
      line(`**Lineage:** ${lead}What Wi-Fi 7 adds: ${md(tab.wifi7Adds)}`);
      line();
    }
    for (const id of tab.scenarioIds ?? []) {
      const s = scenarioById.get(id);
      if (!s) continue;
      line(`**Healthcare scenario — ${md(s.location)}** (devices: ${s.deviceTypes.join(', ')})`);
      line();
      line(`- Problem: ${md(s.problem)}`);
      line(`- What Wi-Fi 7 supports: ${md(s.outcomeSupported)}`);
      line();
    }

    tab.beats.forEach((b, si) => {
      line(`### Step ${si + 1} — ${md(b.caption?.headline ?? b.heading)}`);
      line();
      const hotspots = b.hotspots ?? [];
      const onScreen = [sentence(`${md(b.caption?.headline)} / ${md(b.caption?.takeaway)}`), md(b.sceneDescription)];
      if (hotspots.length) onScreen.push(`Hotspots: ${hotspots.map((h) => termById.get(h.term)?.term ?? h.term).join(', ')}.`);
      line(`**On screen:** ${onScreen.join(' ')}`);
      line();
      if (b.callout) {
        line(`**Callout — ${md(b.callout.title)}:**`);
        line();
        for (const p of b.callout.points) line(`- ${md(p)}`);
        line();
      }
      line(`**Say (leadership):** ${md(b.heading)}.`);
      line();
      line(md(b.body));
      if (b.bottomLine) {
        line();
        line(`**Bottom line:** ${md(b.bottomLine)}`);
      }
      line();
      const technical = [b.caption?.technical, b.deepDive, ...hotspots.map((h) => h.technical)].filter(Boolean).map(md);
      line(`**Technical depth:** ${technical.length ? technical.join(' ') : 'No extra technical layer on this step.'}`);
      line();
      const terms = termsIn(b.heading, b.body, b.bottomLine, b.deepDive, b.caption?.headline, b.caption?.takeaway, b.caption?.technical, ...(b.callout?.points ?? [])).concat(hotspots.map((h) => h.term));
      const uniqueTerms = [...new Set(terms)].filter((id) => termById.has(id));
      if (uniqueTerms.length) {
        line('**Terms:**');
        line();
        for (const id of uniqueTerms) line(`- ${termById.get(id).term} — ${termById.get(id).short ?? termById.get(id).definition}`);
        line();
      }
      const stepClaims = [...new Set([
        ...claimsIn(b.body, b.bottomLine, b.deepDive, b.caption?.takeaway, b.caption?.technical, ...(b.callout?.points ?? []), ...hotspots.map((h) => h.technical)),
        ...hotspots.map((h) => h.claim).filter(Boolean)
      ])].filter((id) => claimById.has(id));
      line('**Figures:**');
      line();
      if (stepClaims.length) {
        line('| Figure | Value | Source | Where |');
        line('|---|---|---|---|');
        for (const id of stepClaims) {
          const c = claimById.get(id);
          const src = c.sources[0];
          const ref = references.find((r) => r.id === src?.referenceId);
          line(`| ${cell(c.statement)} | ${cell(value(c))}${c.method === 'illustrative' ? ' (illustrative)' : ''} | ${ref ? `S${sourceNo.get(ref.id)} ${cell(ref.title)}` : '—'} | ${cell(src?.locator ?? '—')} |`);
        }
      } else {
        line('No figures cited on this step.');
      }
      line();
      line('**Likely questions:**');
      line();
      if (b.questions?.length) {
        for (const q of b.questions) line(`- **Q (${q.audience ?? 'both'}):** ${md(q.q)} **A:** ${md(q.a)}`);
      } else {
        line('- None written yet.');
      }
      line();
    });

    if (tab.keyFigures?.length) {
      const gens = tab.compareGenerations.filter((g) => tab.keyFigures.some((k) => g in (k.values ?? {})));
      line('### Key figures');
      line();
      line(`| Figure | ${gens.map((g) => `${genById.get(g)?.name} (${genById.get(g)?.ieee})`).join(' | ')} | Qualifier | Sources |`);
      line(`|---|${gens.map(() => '---').join('|')}|---|---|`);
      for (const k of tab.keyFigures) {
        const vals = gens.map((g) => cell(k.values?.[g] ?? 'n/a') + (k.unit && typeof k.values?.[g] === 'number' ? ` ${cell(k.unit)}` : ''));
        const refs = Object.values(k.claimIds ?? {}).flatMap((id) => (claimById.get(id)?.sources ?? []).map((s) => s.referenceId));
        line(`| ${cell(k.metric)}${k.note ? ` — ${cell(k.note)}` : ''} | ${vals.join(' | ')} | ${QUALIFIER_LABEL[k.qualifier] ?? k.qualifier ?? '—'} | ${refs.length ? marker(refs) : '—'} |`);
      }
      line();
    }

    if (tab.sections?.length) {
      line('### Deep sections (Technical)');
      line();
      for (const s of tab.sections) {
        line(`#### ${md(s.heading)}`);
        line();
        line(md(s.body));
        line();
      }
    }
  });

  // Reference-page content (the references chapter's own sections).
  for (const tab of tabs.filter((t) => t.kind === 'references')) {
    line(`## ${tab.title}`);
    line();
    line(md(tab.summary));
    line();
    for (const s of tab.sections ?? []) {
      line(`### ${md(s.heading)}`);
      line();
      line(md(s.body));
      line();
    }
  }

  line('## Generations');
  line();
  line('| Generation | IEEE | Year | Status |');
  line('|---|---|---|---|');
  for (const g of generations) line(`| ${cell(g.name)} | ${cell(g.ieee)} | ${cell(g.year)} | ${cell(g.status)} |`);
  line();

  line('## Glossary');
  line();
  for (const g of [...glossary].sort((a, b) => a.term.localeCompare(b.term))) {
    const short = g.short ? ` Short: ${g.short}` : '';
    line(`- **${g.term}**${g.expansion ? ` (${g.expansion})` : ''}: ${g.definition}${short}`);
  }
  line();

  line('## Claims register');
  line();
  for (const c of claims) {
    line(`### ${c.id}`);
    line();
    line(`${md(c.statement)} — value: ${value(c)}; method: ${c.method}; kind: ${c.kind}.`);
    for (const s of c.sources) {
      line(`- ${marker([s.referenceId])} ${s.locator}${s.excerpt ? ` — “${s.excerpt}”` : ''}`);
    }
    if (c.derivation?.explanation) line(`- Derivation: ${c.derivation.explanation}`);
    const v = c.verification ?? {};
    line(`- Verification: ${v.verifiedOn ? `${v.verifiedOn} by ${v.verifiedBy}` : 'not yet verified'}${v.notes ? ` (${v.notes})` : ''}`);
    line();
  }

  line('## References');
  line();
  for (const tier of [1, 2]) {
    line(`### Tier ${tier}`);
    line();
    for (const r of references.filter((x) => x.tier === tier && !x.retired)) {
      line(`- **S${sourceNo.get(r.id)}** ${r.title}. ${[r.identifier, r.edition, r.date].filter(Boolean).join(', ')} (${r.status}, ${r.access}). ${r.url}`);
    }
    line();
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root, OUTPUT);
  const fresh = buildTalkTrack();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== fresh) {
      console.error(`${OUTPUT} is out of date. Run: node scripts/talk-track.mjs`);
      process.exit(1);
    }
    console.log(`${OUTPUT} is up to date.`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, fresh);
    console.log(`Talk track: ${OUTPUT} (${fresh.split('\n').length} lines)`);
  }
}
